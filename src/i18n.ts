function getUiLanguage(): string {
  try {
    return chrome.i18n.getUILanguage();
  } catch {
    return navigator.language;
  }
}

export const isChinese = /^zh(?:-|$)/i.test(getUiLanguage());
export const locale = isChinese ? "zh-CN" : "en-US";

export function t(key: MessageKey, params: MessageParams = {}): string {
  const dictionary = isChinese ? messages.zh : messages.en;
  return dictionary[key].replace(/\{(\w+)\}/g, (_match, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}

export function canvasCount(count: number): string {
  if (isChinese) return `${count} 个画布`;
  return `${count} ${count === 1 ? "canvas" : "canvases"}`;
}

export function applyDocumentLocale(): void {
  document.documentElement.lang = locale;
}
